const express = require("express");
const bcrypt = require("bcrypt");
const crypto = require("crypto");

const Admin = require("./Admin");
const requireAdmin = require("./adminAuth");

const router = express.Router();

/* =========================================================
FINORA ADMIN SECURITY SETTINGS
========================================================= */

const RECOVERY_SESSION_MINUTES = 10;

/* =========================================================
GENERATE SECURE RECOVERY KEY

The actual recovery key is returned only when the
permanent Admin account is securely created.

MongoDB stores only the bcrypt hash.
========================================================= */

function generateRecoveryKey() {

return (
    crypto.randomBytes(24).toString("base64url")
);

}
/* =========================================================
ONE-TIME PERMANENT ADMIN ACCOUNT SETUP

SECURITY:
- Requires ADMIN_SETUP_KEY from Render environment variables.
- Works only when no Admin account exists.
- Cannot create a second Admin account.
- Password is hashed with bcrypt.
- Recovery key is generated by the server.
- Only the recovery-key hash is stored in MongoDB.
- The plain recovery key is returned only once.
========================================================= */

router.post(
"/setup",
async (req, res) => {

    try {

        const {
            setupKey,
            username,
            email,
            password,
            confirmPassword
        } = req.body;


        /* =============================================
           VERIFY PRIVATE SETUP KEY
        ============================================= */

        if (
            !setupKey ||
            !process.env.ADMIN_SETUP_KEY ||
            setupKey !==
                process.env.ADMIN_SETUP_KEY
        ) {

            return res.status(403).json({

                success: false,

                message:
                    "Admin setup authorization failed."
            });
        }


        /* =============================================
           PREVENT SECOND ADMIN CREATION
        ============================================= */

        const existingAdmin =
            await Admin.findOne({});


        if (existingAdmin) {

            return res.status(403).json({

                success: false,

                message:
                    "Admin setup has already been completed."
            });
        }


        /* =============================================
           VALIDATE USERNAME
        ============================================= */
const cleanUsername =
    String(
        username || ""
    )
        .trim()
        .toLowerCase();


        if (
            cleanUsername.length < 3
        ) {

            return res.status(400).json({

                success: false,

                message:
                    "Admin username must be at least 3 characters."
            });
        }


        /* =============================================
           VALIDATE EMAIL
        ============================================= */

        const cleanEmail =
            String(
                email || ""
            )
                .trim()
                .toLowerCase();


        if (
            !cleanEmail ||
            !cleanEmail.includes("@")
        ) {

            return res.status(400).json({

                success: false,

                message:
                    "A valid Admin email address is required."
            });
        }


        /* =============================================
           VALIDATE PASSWORD
        ============================================= */

        const cleanPassword =
            String(
                password || ""
            );


        const cleanConfirmPassword =
            String(
                confirmPassword || ""
            );


        if (
            cleanPassword.length < 6
        ) {

            return res.status(400).json({

                success: false,

                message:
                    "Admin password must be at least 6 characters."
            });
        }


        if (
            cleanPassword !==
            cleanConfirmPassword
        ) {

            return res.status(400).json({

                success: false,

                message:
                    "Passwords do not match."
            });
        }


        /* =============================================
           GENERATE PASSWORD HASH
        ============================================= */

        const passwordHash =
            await bcrypt.hash(
                cleanPassword,
                12
            );


        /* =============================================
           GENERATE RECOVERY KEY
        ============================================= */

        const recoveryKey =
            generateRecoveryKey();


        const recoveryKeyHash =
            await bcrypt.hash(
                recoveryKey,
                12
            );


        /* =============================================
           CREATE PERMANENT ADMIN
        ============================================= */

        const admin =
            new Admin({

                username:
                    cleanUsername,

                email:
                    cleanEmail,

                passwordHash,

                recoveryKeyHash,

                recoveryKeyVersion:
                    1,

                status:
                    "active"
            });


        await admin.save();


        /* =============================================
           RETURN RECOVERY KEY ONCE

           MongoDB DOES NOT receive the plain key.
        ============================================= */

        return res.status(201).json({

            success: true,

            message:
                "FINORA permanent Admin account created successfully.",

            admin: {

                username:
                    admin.username,

                email:
                    admin.email
            },

            recoveryKey

        });

    } catch (error) {

        console.error(
            "❌ FINORA ADMIN SETUP ERROR:",
            error
        );


        return res.status(500).json({

            success: false,

            message:
                "FINORA could not create the Admin account."
        });
    }
}
);
/* =========================================================
LOGIN
========================================================= */

router.post(
"/login",
async (req, res) => {

    try {

        const identifier =
            String(
                req.body.identifier || ""
            )
                .trim()
                .toLowerCase();

        const password =
            String(
                req.body.password || ""
            );


        if (
            !identifier ||
            !password
        ) {

            return res.status(400).json({

                success: false,

                message:
                    "Admin username/email and password are required."
            });
        }


        const admin =
            await Admin.findOne({

                $or: [
                    {
                        username:
                            identifier
                    },
                    {
                        email:
                            identifier
                    }
                ]

            }).select(
                "+passwordHash"
            );


        if (!admin) {

            return res.status(401).json({

                success: false,

                message:
                    "Invalid Admin credentials."
            });
        }


        if (
            admin.status !==
            "active"
        ) {

            return res.status(403).json({

                success: false,

                message:
                    "This Admin account is disabled."
            });
        }


        const passwordMatches =
            await bcrypt.compare(
                password,
                admin.passwordHash
            );


        if (!passwordMatches) {

            return res.status(401).json({

                success: false,

                message:
                    "Invalid Admin credentials."
            });
        }


        /*
           Store only the Admin identity in the
           authenticated session.

           The normal user session uses userId.
           Admin authentication uses adminId.
        */

        req.session.adminId =
            admin._id.toString();


        /*
           Remove any temporary recovery state from
           the same session after successful login.
        */

        delete req.session.adminRecoveryId;
        delete req.session.adminRecoveryExpires;


        admin.lastLogin =
            new Date();

        await admin.save();


        await new Promise(
            (resolve, reject) => {

                req.session.save(
                    error => {

                        if (error) {

                            return reject(
                                error
                            );
                        }

                        resolve();
                    }
                );
            }
        );


        return res.status(200).json({

            success: true,

            message:
                "Admin login successful.",

            admin: {

                id:
                    admin._id,

                username:
                    admin.username,

                email:
                    admin.email,

                status:
                    admin.status,

                lastLogin:
                    admin.lastLogin
            }
        });

    } catch (error) {

        console.error(
            "❌ FINORA ADMIN LOGIN ERROR:",
            error
        );


        return res.status(500).json({

            success: false,

            message:
                "FINORA Admin login failed."
        });
    }
}

);

